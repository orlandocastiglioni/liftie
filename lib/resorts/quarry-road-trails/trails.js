import select from '../../select.js';
import { findText } from '../../tools/domutil.js';

/**
 * quarryroad.org/conditions is a Squarespace page whose only live data is an
 * iframe onto a "publish to web" Google Sheet. resort.json points trails at
 * that sheet's pubhtml view - the rm=minimal&widget=false&chrome=false params
 * are load bearing: without them Google serves a javascript shell with no
 * table at all. The range param the site's own iframe carries is dropped so
 * the feed cannot truncate when rows are added.
 *
 * Every row of the sheet is a <tr> with a leading row-number <th> followed by
 * five <td> for columns A-E, so cells are indexed by position (the s1..s20 CSS
 * classes are regenerated by Google on every edit and must never be keyed on):
 *   td[0] status glyph   td[1] difficulty glyph   td[2] trail name
 *   td[3] value column (summary block only)       td[4] grooming note
 * Requiring a known status glyph in td[0] and a name in td[2] is enough to
 * drop both the 14-row summary header and the section headings
 * ("Charlie's Meadow", "Alpine / Downhill Trails", ...).
 *
 * The sheet's whole vocabulary is glyphs, none of which liftie knows:
 * '√' (U+221A) is open and 'X' is closed - coerce would read the check as
 * 'scheduled'; '⬤' / '◼' / '◆' are easiest / more difficult / most difficult.
 * Both maps are therefore explicit here.
 *
 * The three "Alpine / Downhill Trails" rows are the rope-tow hill; they are
 * reported exactly like the 26 nordic trails and are kept in sheet order. The
 * two park rows ("Nordic Terrain Park", "Terrain Park") are published with a
 * blue square rather than a park marker, and that published level is what is
 * reported - the sheet is the authority on its own ratings.
 */
const statuses = {
  '√': 'open',
  X: 'closed'
};

const levels = {
  '⬤': 'green',
  '◼': 'blue',
  '◆': 'black'
};

export default function parse(dom) {
  const rows = [];
  for (const row of select(dom, 'table.waffle tbody tr')) {
    const cells = (row.children ?? []).filter(cell => cell.name === 'td');
    const status = statuses[findText(cells[0])?.trim()];
    const name = findText(cells[2])?.trim();
    if (!status || !name) {
      continue;
    }
    rows.push({
      name,
      status,
      level: levels[findText(cells[1])?.trim()]
    });
  }
  return rows;
}
